class TestPlanStatus:
    PLANNED = "PLANNED"
    GENERATED = "GENERATED"
    #: A strategy with no available engine/generator for this target.
    UNSUPPORTED = "UNSUPPORTED"
    EXECUTED = "EXECUTED"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"


class TestPlan(BaseModel):
    """A validated spec plus everything KavachX derived around it.

    Deliberately not a ``StrictModel``: this is KavachX's own record, assembled after validation,
    and it carries fields a model is never allowed to set (the resolved engine, the generated
    harness path, the marker values).
    """

    model_config = ConfigDict(arbitrary_types_allowed=True)

    spec: TestSpec
    #: Stable id: sha256 over the canonical spec plus the target's index id.
    plan_id: str = ""
    candidate_ref: str = ""
    finding_handle: str = ""
    status: str = TestPlanStatus.PLANNED
    #: Chosen by KavachX from the detected language and installed toolchain.
    engine: str = ""
    engine_available: bool = False
    engine_reason: str = ""
    language: str = ""
    #: Workspace-relative path of the generated harness, once generated.
    harness_path: str = ""
    harness_sha256: str = ""
    #: The argv the sandbox will run. Built by KavachX; never model-supplied.
    command: list[str] = Field(default_factory=list)
    #: Marker values injected by KavachX for marker/canary oracles.
    markers: dict[str, str] = Field(default_factory=dict)
    #: Why this plan exists, in evidence terms.
    provenance: dict[str, Any] = Field(default_factory=dict)
    notes: list[str] = Field(default_factory=list)

    def as_dict(self) -> dict[str, Any]:
        return {
            "plan_id": self.plan_id,
            "candidate_ref": self.candidate_ref,
            "finding_handle": self.finding_handle,
            "status": self.status,
            "engine": self.engine,
            "engine_available": self.engine_available,
            "engine_reason": self.engine_reason,
            "language": self.language,
            "harness_path": self.harness_path,
            "harness_sha256": self.harness_sha256,
            "command": self.command,
            "spec": self.spec.as_dict(),
            "provenance": self.provenance,
            "notes": self.notes,
        }


def plan_id_for(spec: TestSpec, *, index_id: str) -> str:
    """Reproducible plan identity.

    Includes the index id so the same spec against a different commit is a different plan — a
    harness is only meaningful against the tree it was generated for.
    """
    from app.core.hashing import sha256_json

    return sha256_json({"spec": spec.as_dict(), "index_id": index_id})
