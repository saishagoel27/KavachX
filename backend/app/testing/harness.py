def _python_differential(plan: TestPlan, workspace: Path, descriptor: Any) -> GeneratedHarness:
    """Record a response hash per input so before/after builds can be compared byte-for-byte."""
    spec = plan.spec
    requests = _request_payloads(spec) or [{}]
    content = (
        _banner(plan)
        # Before/after comparison must see exactly what a real invocation produces.
        + _python_driver_preamble(plan, descriptor, mode="subprocess")
        + f'''
import hashlib

REQUESTS = {_py_lit(requests)}


def main():
    rows = []
    for index, request in enumerate(REQUESTS):
        ok, rendered, error = drive(request)
        rows.append({{
            "index": index,
            "ok": ok,
            # The hash, not the body: a differential comparison needs equality, and storing the
            # body would put target output into an artifact for no benefit.
            "response_sha256": hashlib.sha256(rendered.encode("utf-8")).hexdigest(),
            "error_class": error.strip().splitlines()[-1][:200] if error else "",
        }})
    out = {{"cases": rows}}
    os.makedirs({_py_lit(HARNESS_DIR + "/out")}, exist_ok=True)
    with open({_py_lit(f"{HARNESS_DIR}/out/{_stem(plan)}.json")}, "w", encoding="utf-8") as fh:
        json.dump(out, fh, sort_keys=True)
    print(json.dumps(out, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''
    )
    path = f"{HARNESS_DIR}/{_stem(plan)}.py"
    report = f"{HARNESS_DIR}/out/{_stem(plan)}.json"
    return GeneratedHarness(
        ok=True,
        path=path,
        content=content,
        command=["python", path],
        artifacts=[report],
        notes=["Response hashes per input, for before/after comparison."],
    )


