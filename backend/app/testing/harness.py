# ---------------------------------------------------------------------------
def attach(plan: TestPlan, harness: GeneratedHarness) -> TestPlan:
    """Fold a generated harness back onto its plan."""
    if not harness.ok:
        plan.status = TestPlanStatus.UNSUPPORTED
        plan.notes.append(harness.error)
        return plan
    plan.status = TestPlanStatus.GENERATED
    plan.harness_path = harness.path
    plan.harness_sha256 = harness.sha256
    plan.command = harness.command
    plan.markers = harness.markers
    plan.notes.extend(harness.notes)
    return plan
