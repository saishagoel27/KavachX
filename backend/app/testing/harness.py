"""Harness generation — KavachX writes the code, the spec supplies only values.

This is where a :class:`~app.testing.specs.TestSpec` becomes something executable, and it is the
single most security-sensitive module in the testing subsystem. The rule it enforces:

    **No string from a model ever becomes code.**

Every harness is produced from a template authored here. The spec contributes *values* — a target
symbol, a payload string, a timeout, a field name — and each value is inserted through
``json.dumps`` or as an argv element, never by string concatenation into a code position. A payload
containing ``"); os.system("rm -rf /`` therefore lands in the generated file as a quoted Python
string literal and stays data.

The generated harness is written into ``_kavachx/tests/`` inside the workspace, which is already
excluded from the pinned-source hash and preserved across gauntlet resets. It is collected as a
run artifact, so the demo's "the generated test is saved" requirement is satisfied by the same
mechanism that makes the test auditable.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from app.core.hashing import sha256_text
from app.core.logging import get_logger
from app.discovery.base import CANARY_CONTENT, CANARY_FILENAME, POV_MARKER
from app.testing.specs import TestPlan, TestPlanStatus, TestSpec

logger = get_logger(__name__)

#: Where generated harnesses live inside the workspace.
HARNESS_DIR = "_kavachx/tests"

#: A generated file always carries this banner. It makes a harness identifiable in a diff, in an
#: artifact listing, and in a target repository if one is ever accidentally copied there.
_BANNER = """# GENERATED BY KAVACHX — DO NOT EDIT
#
# This harness was generated from a validated TestSpec by app/testing/harness.py.
# Every value below was inserted as a data literal; no model-supplied text is executable here.
#
#   plan_id : {plan_id}
#   target  : {target}
#   strategy: {strategy}
#   oracle  : {oracle}
#   property: {prop}
"""


@dataclass
class GeneratedHarness:
    ok: bool = False
    #: Workspace-relative path.
    path: str = ""
    content: str = ""
    sha256: str = ""
    #: The argv the sandbox runs. Built here, never model-supplied.
    command: list[str] = field(default_factory=list)
    #: Marker values injected for marker/canary oracles.
    markers: dict[str, str] = field(default_factory=dict)
    #: Files the harness writes that should be collected back out of the sandbox.
    artifacts: list[str] = field(default_factory=list)
    error: str = ""
    notes: list[str] = field(default_factory=list)

    def as_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "path": self.path,
            "sha256": self.sha256,
            "command": self.command,
            # Markers are KavachX-generated constants, not secrets: they must appear in the
            # record because reproducing a finding requires knowing which marker was planted.
            "markers": dict(self.markers),
            "artifacts": self.artifacts,
            "error": self.error,
            "notes": self.notes,
        }


def _banner(plan: TestPlan) -> str:
    return _BANNER.format(
        plan_id=plan.plan_id[:16],
        target=plan.spec.target,
        strategy=plan.spec.strategy,
        oracle=plan.spec.oracle.kind,
        prop=plan.spec.expected_security_property[:120].replace("\n", " "),
    )


#: Types a spec value may have. Anything else is a bug in the spec layer, not something to render.
_PLAIN_TYPES = (str, int, float, bool, type(None), list, tuple, dict)


def _assert_plain(value: Any) -> None:
    """Reject anything that is not a plain JSON-shaped value.

    This is the guard that makes literal rendering safe: ``repr`` of an unexpected object emits
    ``<object at 0x...>``, which is a syntax error in the generated file. Failing loudly here
    surfaces it as a harness-generation error instead.
    """
    if not isinstance(value, _PLAIN_TYPES):
        raise TypeError(
            f"cannot render {type(value).__name__} as a literal; spec values must be plain "
            "JSON-shaped data"
        )
    if isinstance(value, (list, tuple)):
        for item in value:
            _assert_plain(item)
    elif isinstance(value, dict):
        for key, item in value.items():
            if not isinstance(key, str):
                raise TypeError("literal dict keys must be strings")
            _assert_plain(item)


def _py_lit(value: Any) -> str:
    """Render a **Python** literal for a value from the spec.

    ``repr``, not ``json.dumps``. JSON is *not* a subset of Python literal syntax: it renders
    booleans as ``true``/``false`` and null as ``null``, none of which are Python. Using
    ``json.dumps`` here produced generated harnesses containing ``if true:`` that died with
    ``NameError: name 'true' is not defined`` at line 1 of execution — a whole strategy silently
    failing to run, reported as "the oracle did not fire".

    ``repr`` of any value that passes :func:`_assert_plain` is a valid Python literal, and nested
    containers are handled correctly by recursion inside ``repr`` itself.
    """
    _assert_plain(value)
    return repr(value)


def _js_lit(value: Any) -> str:
    """Render a **JavaScript/JSON** literal. Here ``json.dumps`` is exactly right."""
    _assert_plain(value)
    return json.dumps(value, ensure_ascii=True)


