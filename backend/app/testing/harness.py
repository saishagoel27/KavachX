def _c_libfuzzer(plan: TestPlan, workspace: Path, descriptor: Any) -> GeneratedHarness:
    """A libFuzzer entrypoint plus a sanitizer-instrumented build command.

    The target function is called through a declared prototype rather than by including a header
    KavachX has not verified exists. If the symbol does not link, the build fails loudly at
    compile time — which is the honest outcome — instead of the harness silently testing nothing.
    """
    spec = plan.spec
    target_file = spec.target.split(":")[0]
    target_fn = spec.target.split(":")[-1] if ":" in spec.target else "LLVMFuzzerTestOneInput"
    stem = _stem(plan)

    content = f'''/* GENERATED BY KAVACHX — DO NOT EDIT
 *
 * plan_id : {plan.plan_id[:16]}
 * target  : {spec.target}
 * oracle  : {spec.oracle.kind}
 * property: {spec.expected_security_property[:100]}
 */
#include <stddef.h>
#include <stdint.h>
#include <string.h>
#include <stdlib.h>

/* Declared, not included: KavachX does not assume a header path it has not confirmed.
 *
 * The signature (const char *, size_t) is an ASSUMPTION. If the real target takes something
 * else, this fails at compile or link time — which is the honest outcome, and is reported as an
 * engine problem rather than as a test that passed. It is never reported as a clean result. */
extern void {target_fn}(const char *input, size_t length);

int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {{
    if (size == 0 || size > 65536) {{
        return 0;
    }}
    char *buffer = (char *) malloc(size + 1);
    if (buffer == NULL) {{
        return 0;
    }}
    memcpy(buffer, data, size);
    buffer[size] = '\\0';
    {target_fn}(buffer, size);
    free(buffer);
    return 0;
}}
'''
    path = f"{HARNESS_DIR}/{stem}.c"
    iterations = spec.fuzz.max_iterations if spec.fuzz else 2000
    return GeneratedHarness(
        ok=True,
        path=path,
        content=content,
        # Build and run are separate steps; the caller runs the build first and reports a compile
        # failure as an engine problem rather than as a clean test.
        command=[
            "clang",
            "-g",
            "-O1",
            "-fsanitize=fuzzer,address,undefined",
            "-fno-omit-frame-pointer",
            path,
            target_file,
            "-o",
            f"{HARNESS_DIR}/{stem}.bin",
        ],
        artifacts=[],
        markers={},
        notes=[
            "clang with -fsanitize=fuzzer,address,undefined.",
            f"run: {HARNESS_DIR}/{stem}.bin -runs={iterations} "
            f"-artifact_prefix={HARNESS_DIR}/out/",
        ],
    )


