def generate(
    plan: TestPlan,
    *,
    workspace: Path,
    descriptor: Any = None,
) -> GeneratedHarness:
    """Generate the harness for ``plan``. Dispatches on (language, strategy)."""
    spec = plan.spec
    language = plan.language or "python"
    key = (language, spec.strategy)

    generator = {
        ("python", "unit"): _python_unit,
        ("python", "regression"): _python_unit,
        ("python", "mutation"): _python_mutation,
        ("python", "property"): _python_property,
        ("python", "fuzz"): _python_fuzz,
        ("python", "differential"): _python_differential,
        ("c", "fuzz"): _c_libfuzzer,
        ("c", "unit"): _c_libfuzzer,
        ("c", "regression"): _c_libfuzzer,
        ("javascript", "property"): _js_property,
        ("javascript", "unit"): _js_unit,
        ("javascript", "regression"): _js_unit,
        ("go", "fuzz"): _go_fuzz,
    }.get(key)

    if generator is None:
        return GeneratedHarness(
            error=(
                f"KavachX has no harness generator for ({language}, {spec.strategy}). The "
                f"{spec.strategy} strategy did NOT run for this target."
            )
        )

    try:
        harness = generator(plan, workspace, descriptor)
    except Exception as exc:  # pragma: no cover - generator bug, must not kill the run
        logger.exception("testing.harness_generation_failed", plan=plan.plan_id[:16])
        return GeneratedHarness(
            error=f"harness generation raised {type(exc).__name__}: {str(exc)[:300]}"
        )

    if harness.ok and harness.content:
        target = workspace / harness.path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(harness.content, encoding="utf-8", newline="\n")
        harness.sha256 = sha256_text(harness.content)
        logger.info(
            "testing.harness_generated",
            plan=plan.plan_id[:16],
            path=harness.path,
            strategy=spec.strategy,
            engine=plan.engine,
            bytes=len(harness.content),
        )
    return harness


def _stem(plan: TestPlan) -> str:
    """A filesystem-safe stem derived from the plan id, not from model-supplied text."""
    return f"kx_{plan.spec.strategy}_{plan.plan_id[:12]}"


def _request_payloads(spec: TestSpec) -> list[dict[str, Any]]:
    """Build the concrete request objects the harness will send.

    The template comes from the spec but is rebuilt here field by field, so a template key cannot
    smuggle in a nested structure the harness does not expect.
    """
    out: list[dict[str, Any]] = []
    template = {str(k): v for k, v in (spec.request_template or {}).items()}
    if not spec.payloads:
        return [template] if template else []
    for payload in spec.payloads:
        request = dict(template)
        if spec.payload_field:
            request[spec.payload_field] = payload
        out.append(request)
    return out


